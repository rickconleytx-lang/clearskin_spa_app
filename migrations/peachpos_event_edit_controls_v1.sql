BEGIN;

-- Peach Suite Pro
-- PeachPOS Event Calendar Edit Controls V1
--
-- Revision protection, exclusive edit leases,
-- and permanent append-only editing history.
--
-- Create-only migration.
-- Apply only after a verified Local database backup.
-- Do not apply to Production without authorization.

-- =====================================================
-- 1. EVENT REVISION
-- =====================================================

ALTER TABLE public.event_calendar_events
ADD COLUMN event_revision BIGINT NOT NULL DEFAULT 1;

ALTER TABLE public.event_calendar_events
ADD CONSTRAINT chk_event_calendar_event_revision
CHECK (event_revision >= 1);

-- Existing saved events begin at revision 1.
-- Successful edits will increment this value.

-- =====================================================
-- 2. EXCLUSIVE EVENT EDIT LEASES
-- =====================================================

CREATE TABLE public.event_calendar_edit_locks (

    spa_id INTEGER NOT NULL,
    business_unit_id INTEGER NOT NULL,
    event_id BIGINT NOT NULL,

    editor_user_id INTEGER NOT NULL,

    -- Unique token for one browser editing session.
    lock_token UUID NOT NULL UNIQUE,

    -- Revision observed when the lock was acquired.
    base_revision BIGINT NOT NULL,

    acquired_at TIMESTAMPTZ NOT NULL,
    last_activity_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,

    PRIMARY KEY (
        spa_id, business_unit_id, event_id
    ),

    CONSTRAINT fk_event_edit_lock_event
        FOREIGN KEY (
            spa_id, business_unit_id, event_id
        )
        REFERENCES public.event_calendar_events (
            spa_id, business_unit_id, event_id
        )
        ON DELETE RESTRICT,

    CONSTRAINT fk_event_edit_lock_editor
        FOREIGN KEY (editor_user_id)
        REFERENCES public.users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_event_edit_lock_revision
        CHECK (base_revision >= 1),

    CONSTRAINT chk_event_edit_lock_times
        CHECK (
            last_activity_at >= acquired_at
            AND expires_at > last_activity_at
            AND expires_at <=
                last_activity_at + INTERVAL '15 minutes'
        )
);

CREATE INDEX idx_event_edit_lock_expiration
ON public.event_calendar_edit_locks (
    expires_at
);

-- Acquisition must be atomic.
-- An existing active lease must not be overwritten.
-- Expired leases may be replaced transactionally.
-- Renewal requires the current editor and token.
-- All lease times must use the database clock.

-- =====================================================
-- 3. PERMANENT EVENT EDIT HISTORY
-- =====================================================

CREATE TABLE public.event_calendar_edit_history (

    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    spa_id INTEGER NOT NULL,
    business_unit_id INTEGER NOT NULL,
    event_id BIGINT NOT NULL,

    action_type VARCHAR(40) NOT NULL,

    revision_before BIGINT NOT NULL,
    revision_after BIGINT NOT NULL,

    actor_user_id INTEGER NOT NULL,

    -- Preserves the historical editor's display name.
    actor_display_name VARCHAR(200) NOT NULL,

    -- Field-level before/after changes.
    changes_json JSONB NOT NULL,

    changed_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_edit_history_event
        FOREIGN KEY (
            spa_id, business_unit_id, event_id
        )
        REFERENCES public.event_calendar_events (
            spa_id, business_unit_id, event_id
        )
        ON DELETE RESTRICT,

    CONSTRAINT fk_event_edit_history_actor
        FOREIGN KEY (actor_user_id)
        REFERENCES public.users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_event_edit_history_action
        CHECK (LENGTH(BTRIM(action_type)) > 0),

    CONSTRAINT chk_event_edit_history_actor_name
        CHECK (LENGTH(BTRIM(actor_display_name)) > 0),

    CONSTRAINT chk_event_edit_history_revisions
        CHECK (
            revision_before >= 1
            AND revision_after = revision_before + 1
        ),

    CONSTRAINT chk_event_edit_history_json
        CHECK (jsonb_typeof(changes_json) = 'object'),

    CONSTRAINT uq_event_edit_history_revision
        UNIQUE (
            spa_id, business_unit_id,
            event_id, revision_after
        )
);

CREATE INDEX idx_event_edit_history_lookup
ON public.event_calendar_edit_history (
    spa_id,
    business_unit_id,
    event_id,
    changed_at DESC,
    history_id DESC
);

-- =====================================================
-- 4. APPEND-ONLY AUDIT PROTECTION
-- =====================================================

CREATE FUNCTION public.guard_event_edit_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    RAISE EXCEPTION
        'Event edit history is append-only.'
        USING ERRCODE = '23514';

    RETURN NULL;

END;
$$;

CREATE TRIGGER trg_event_edit_history_append_only
BEFORE UPDATE OR DELETE
ON public.event_calendar_edit_history
FOR EACH ROW
EXECUTE FUNCTION public.guard_event_edit_history();

COMMIT;
