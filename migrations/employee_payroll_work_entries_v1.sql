BEGIN;

-- =====================================================
-- PEACH SUITE PRO
-- EMPLOYEE PAYROLL WORK ENTRIES V1
--
-- Operational Hours & Payroll foundation.
-- Separate from existing Employee Compensation.
-- Additive migration.
-- =====================================================

CREATE TABLE public.employee_payroll_work_entries (
    work_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    spa_id INTEGER NOT NULL,
    business_unit_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,

    work_date DATE NOT NULL,
    entry_type VARCHAR(20) NOT NULL,

    regular_hours NUMERIC(8,2) NOT NULL DEFAULT 0,
    overtime_hours NUMERIC(8,2) NOT NULL DEFAULT 0,
    days_worked NUMERIC(6,2) NOT NULL DEFAULT 0,

    clock_in_at TIMESTAMPTZ,
    clock_out_at TIMESTAMPTZ,

    -- Captured rate, not a live lookup.
    rate_snapshot NUMERIC(12,2) NOT NULL,
    overtime_rate_snapshot NUMERIC(12,2),

    -- Historical event label; calendar FK comes later.
    event_name_snapshot VARCHAR(200),

    notes TEXT,

    -- For trusted external-source idempotency.
    source_system VARCHAR(40) NOT NULL DEFAULT 'manual',
    source_reference VARCHAR(160),

    created_by_user_id INTEGER NOT NULL,
    updated_by_user_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Preserve voided entries for audit/history.
    voided_at TIMESTAMPTZ,
    voided_by_user_id INTEGER,
    void_reason TEXT,

    CONSTRAINT fk_payroll_work_entry_membership
        FOREIGN KEY (
            spa_id, business_unit_id, employee_id
        )
        REFERENCES public.employee_business_unit_memberships (
            spa_id, business_unit_id, employee_id
        )
        ON DELETE RESTRICT,

    CONSTRAINT fk_payroll_work_entry_creator
        FOREIGN KEY (created_by_user_id)
        REFERENCES public.users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_payroll_work_entry_updater
        FOREIGN KEY (updated_by_user_id)
        REFERENCES public.users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_payroll_work_entry_void_actor
        FOREIGN KEY (voided_by_user_id)
        REFERENCES public.users(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_payroll_work_entry_type
        CHECK (entry_type IN ('hourly', 'daily', 'event')),

    CONSTRAINT chk_payroll_work_entry_quantities
        CHECK (
            regular_hours >= 0
            AND overtime_hours >= 0
            AND days_worked >= 0
        ),

    CONSTRAINT chk_payroll_work_entry_rates
        CHECK (
            rate_snapshot >= 0
            AND (
                overtime_rate_snapshot IS NULL
                OR overtime_rate_snapshot >= 0
            )
            AND (
                overtime_hours = 0
                OR overtime_rate_snapshot IS NOT NULL
            )
        ),

    CONSTRAINT chk_payroll_work_entry_clock
        CHECK (
            clock_out_at IS NULL
            OR (
                clock_in_at IS NOT NULL
                AND clock_out_at > clock_in_at
            )
        ),

    CONSTRAINT chk_payroll_work_entry_shape
        CHECK (
            (
                entry_type = 'hourly'
                AND days_worked = 0
                AND event_name_snapshot IS NULL
                AND (
                    regular_hours + overtime_hours > 0
                    OR (
                        clock_in_at IS NOT NULL
                        AND clock_out_at IS NULL
                    )
                )
            )
            OR (
                entry_type = 'daily'
                AND days_worked > 0
                AND regular_hours = 0
                AND overtime_hours = 0
                AND overtime_rate_snapshot IS NULL
                AND clock_in_at IS NULL
                AND clock_out_at IS NULL
                AND event_name_snapshot IS NULL
            )
            OR (
                entry_type = 'event'
                AND regular_hours = 0
                AND overtime_hours = 0
                AND days_worked = 0
                AND overtime_rate_snapshot IS NULL
                AND clock_in_at IS NULL
                AND clock_out_at IS NULL
                AND NULLIF(
                    BTRIM(event_name_snapshot), ''
                ) IS NOT NULL
            )
        ),

    CONSTRAINT chk_payroll_work_entry_source
        CHECK (BTRIM(source_system) <> ''),

    CONSTRAINT chk_payroll_work_entry_void
        CHECK (
            (
                voided_at IS NULL
                AND voided_by_user_id IS NULL
                AND void_reason IS NULL
            )
            OR (
                voided_at IS NOT NULL
                AND voided_by_user_id IS NOT NULL
                AND NULLIF(BTRIM(void_reason), '') IS NOT NULL
            )
        )
);

CREATE INDEX idx_payroll_work_entry_employee_date
    ON public.employee_payroll_work_entries (
        spa_id,
        business_unit_id,
        employee_id,
        work_date DESC,
        work_entry_id DESC
    );

CREATE INDEX idx_payroll_work_entry_workspace_date
    ON public.employee_payroll_work_entries (
        spa_id,
        business_unit_id,
        work_date
    );

CREATE UNIQUE INDEX uq_payroll_work_entry_source
    ON public.employee_payroll_work_entries (
        spa_id,
        business_unit_id,
        source_system,
        source_reference
    )
    WHERE source_reference IS NOT NULL;

COMMENT ON TABLE public.employee_payroll_work_entries IS
    'Workspace-isolated employee hourly, daily, and event '
    'work entries for operational payroll. Historical rates '
    'are snapshotted. Legacy Compensation remains separate.';

COMMENT ON COLUMN
    public.employee_payroll_work_entries.rate_snapshot IS
    'Hourly, daily, or individual event rate recorded for '
    'this work entry; must not be silently replaced by a '
    'later employee default rate.';

COMMIT;
