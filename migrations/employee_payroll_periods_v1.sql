BEFORE INSERT OR UPDATE OR DELETE
ON public.employee_payroll_period_entries
FOR EACH ROW
EXECUTE FUNCTION
    public.guard_payroll_period_entry_allocation();


-- =====================================================
-- PAY PERIOD BOUNDARY AND IDENTITY PROTECTION
-- =====================================================

CREATE FUNCTION public.guard_employee_payroll_period_boundaries()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    boundaries_changed BOOLEAN;
    confirmation_changed BOOLEAN;
    actor_text TEXT;
    actor_id INTEGER;
    confirmation_signal TEXT;
BEGIN
    IF NEW.spa_id IS DISTINCT FROM OLD.spa_id
       OR NEW.business_unit_id
           IS DISTINCT FROM OLD.business_unit_id
       OR NEW.employee_id
           IS DISTINCT FROM OLD.employee_id
    THEN
        RAISE EXCEPTION
            'Saved payroll period employee and workspace '
            'cannot be reassigned.'
            USING ERRCODE = '23514';
    END IF;

    boundaries_changed :=
        NEW.period_start IS DISTINCT FROM OLD.period_start
        OR NEW.period_end IS DISTINCT FROM OLD.period_end
        OR NEW.pay_frequency_snapshot
            IS DISTINCT FROM OLD.pay_frequency_snapshot;

    confirmation_changed :=
        NEW.boundaries_confirmed_by_user_id
            IS DISTINCT FROM OLD.boundaries_confirmed_by_user_id
        OR NEW.boundaries_confirmed_at
            IS DISTINCT FROM OLD.boundaries_confirmed_at;

    IF NOT boundaries_changed
       AND NOT confirmation_changed
    THEN
        RETURN NEW;
    END IF;

    IF OLD.status <> 'draft'
       OR NEW.status <> 'draft'
    THEN
        RAISE EXCEPTION
            'Finalized payroll period boundaries are locked.'
            USING ERRCODE = '23514';
    END IF;

    IF boundaries_changed AND EXISTS (
        SELECT 1
        FROM public.employee_payroll_period_entries pe
        WHERE pe.pay_period_id = OLD.pay_period_id
          AND pe.spa_id = OLD.spa_id
          AND pe.business_unit_id = OLD.business_unit_id
          AND pe.employee_id = OLD.employee_id
    ) THEN
        RAISE EXCEPTION
            'Remove all Draft payroll allocations before '
            'changing pay-period boundaries or frequency.'
            USING ERRCODE = '23514';
    END IF;

    actor_text := NULLIF(
        BTRIM(
            COALESCE(
                current_setting(
                    'psp.payroll_draft_update_actor', true
                ),
                ''
            )
        ),
        ''
    );

    confirmation_signal := current_setting(
        'psp.payroll_boundaries_confirmed', true
    );

    IF actor_text IS NULL
       OR confirmation_signal IS DISTINCT FROM 'yes'
    THEN
        RAISE EXCEPTION
            'Changing payroll boundaries requires '
            'fresh explicit confirmation.'
            USING ERRCODE = '23514';
    END IF;

    SELECT u.user_id
    INTO actor_id
    FROM public.users u
    WHERE u.user_id::TEXT = actor_text;

    IF actor_id IS NULL
       OR NEW.updated_by_user_id IS DISTINCT FROM actor_id
       OR NEW.boundaries_confirmed_by_user_id
           IS DISTINCT FROM actor_id
    THEN
        RAISE EXCEPTION
            'Payroll boundary confirmation actor '
            'must match the authenticated updater.'
            USING ERRCODE = '23514';
    END IF;

    -- Timestamp comes from PostgreSQL itself.
    NEW.boundaries_confirmed_at := clock_timestamp();

    -- One explicit confirmation authorizes one row update.
    PERFORM set_config(
        'psp.payroll_boundaries_confirmed',
        '',
        true
    );

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payroll_period_boundaries
BEFORE UPDATE OF
    spa_id,
    business_unit_id,
    employee_id,
    period_start,
    period_end,
    pay_frequency_snapshot,
    boundaries_confirmed_by_user_id,
    boundaries_confirmed_at
ON public.employee_payroll_periods
FOR EACH ROW
EXECUTE FUNCTION
    public.guard_employee_payroll_period_boundaries();


-- =====================================================
-- PAYROLL APPROVAL FINANCIAL RECONCILIATION
-- =====================================================

CREATE FUNCTION public.guard_employee_payroll_approval_totals()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    totals RECORD;
    expected_fica NUMERIC(14,2);
    expected_deductions NUMERIC(14,2);
    expected_net NUMERIC(14,2);
BEGIN
    -- This guard applies only when Draft becomes Approved.
    IF OLD.status <> 'draft'
       OR NEW.status <> 'approved'
    THEN
        RETURN NEW;
    END IF;

    -- Approval requires a complete calculation snapshot.
    IF NEW.regular_hours_snapshot IS NULL
       OR NEW.overtime_hours_snapshot IS NULL
       OR NEW.days_worked_snapshot IS NULL
       OR NEW.event_count_snapshot IS NULL
       OR NEW.gross_pay_snapshot IS NULL
       OR NEW.fica_percent_snapshot IS NULL
       OR NEW.fica_amount_snapshot IS NULL
       OR NEW.total_deductions_snapshot IS NULL
       OR NEW.estimated_net_snapshot IS NULL
       OR NEW.calculated_at IS NULL
    THEN
        RAISE EXCEPTION
            'Payroll approval requires complete calculation snapshots.'
            USING ERRCODE = '23514';
    END IF;

    -- Aggregate the historically saved earning lines.
    SELECT
        COUNT(*) AS entry_count,

        COALESCE(
            SUM(pe.regular_hours_snapshot), 0
        ) AS regular_hours,

        COALESCE(
            SUM(pe.overtime_hours_snapshot), 0
        ) AS overtime_hours,

        COALESCE(
            SUM(pe.days_worked_snapshot), 0
        ) AS days_worked,

        COUNT(*) FILTER (
            WHERE pe.entry_type_snapshot = 'event'
        ) AS event_count,

        COALESCE(
            SUM(pe.gross_amount_snapshot), 0
        ) AS gross_pay

    INTO totals

    FROM public.employee_payroll_period_entries pe

    WHERE pe.pay_period_id = NEW.pay_period_id
      AND pe.spa_id = NEW.spa_id
      AND pe.business_unit_id = NEW.business_unit_id
      AND pe.employee_id = NEW.employee_id;

    IF totals.entry_count = 0 THEN
        RAISE EXCEPTION
            'Cannot approve a pay period without work entries.'
            USING ERRCODE = '23514';
    END IF;

    -- Every work quantity must reconcile.
    IF NEW.regular_hours_snapshot
            IS DISTINCT FROM totals.regular_hours
       OR NEW.overtime_hours_snapshot
            IS DISTINCT FROM totals.overtime_hours
       OR NEW.days_worked_snapshot
            IS DISTINCT FROM totals.days_worked
       OR NEW.event_count_snapshot
            IS DISTINCT FROM totals.event_count
    THEN
        RAISE EXCEPTION
            'Payroll work quantities do not match allocated entries.'
            USING ERRCODE = '23514';
    END IF;

    -- Gross earnings must match the saved earning lines.
    IF NEW.gross_pay_snapshot
        IS DISTINCT FROM totals.gross_pay
    THEN
        RAISE EXCEPTION
            'Payroll gross pay does not match allocated earnings.'
            USING ERRCODE = '23514';
    END IF;

    -- Each custom deduction with a positive amount
    -- must have a meaningful title.
    IF (
        COALESCE(NEW.deduction_1_amount_snapshot, 0) > 0
        AND NULLIF(
            BTRIM(NEW.deduction_1_title_snapshot), ''
        ) IS NULL
    ) OR (
        COALESCE(NEW.deduction_2_amount_snapshot, 0) > 0
        AND NULLIF(
            BTRIM(NEW.deduction_2_title_snapshot), ''
        ) IS NULL
    ) THEN
        RAISE EXCEPTION
            'Custom payroll deductions require titles.'
            USING ERRCODE = '23514';
    END IF;

    -- FICA is an employee-configured withholding estimate.
    expected_fica := ROUND(
        NEW.gross_pay_snapshot
        * NEW.fica_percent_snapshot / 100,
        2
    );

    IF NEW.fica_amount_snapshot
        IS DISTINCT FROM expected_fica
    THEN
        RAISE EXCEPTION
            'Payroll FICA calculation does not reconcile.'
            USING ERRCODE = '23514';
    END IF;

    expected_deductions := (
        expected_fica
        + COALESCE(NEW.deduction_1_amount_snapshot, 0)
        + COALESCE(NEW.deduction_2_amount_snapshot, 0)
    );

    IF NEW.total_deductions_snapshot
        IS DISTINCT FROM expected_deductions
    THEN
        RAISE EXCEPTION
            'Payroll deduction totals do not reconcile.'
            USING ERRCODE = '23514';
    END IF;

    IF expected_deductions > NEW.gross_pay_snapshot THEN
        RAISE EXCEPTION
            'Payroll deductions cannot exceed gross earnings.'
            USING ERRCODE = '23514';
    END IF;

    expected_net := (
        NEW.gross_pay_snapshot - expected_deductions
    );

    IF NEW.estimated_net_snapshot
        IS DISTINCT FROM expected_net
    THEN
        RAISE EXCEPTION
            'Payroll estimated net pay does not reconcile.'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

