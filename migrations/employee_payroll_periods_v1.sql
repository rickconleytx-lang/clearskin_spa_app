-- =====================================================
-- AUTOMATIC PAY PERIOD AUDIT HISTORY
-- =====================================================

CREATE FUNCTION public.audit_employee_payroll_period()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    audit_action VARCHAR(80);
    audit_actor INTEGER;
    prior_status VARCHAR(20);
    audit_details JSONB;
BEGIN
    IF TG_OP = 'INSERT' THEN
        audit_action := 'period_created';
        audit_actor := NEW.created_by_user_id;
        prior_status := NULL;

    ELSIF OLD.status IS DISTINCT FROM NEW.status THEN
        prior_status := OLD.status;

        IF NEW.status = 'approved' THEN
            audit_action := 'period_approved';
            audit_actor := NEW.approved_by_user_id;

        ELSIF NEW.status = 'paid' THEN
            audit_action := 'period_marked_paid';
            audit_actor := NEW.paid_by_user_id;

        ELSIF NEW.status = 'cancelled' THEN
            audit_action := 'period_cancelled';
            audit_actor := NEW.cancelled_by_user_id;

        ELSE
            RAISE EXCEPTION
                'Unexpected payroll audit transition.';
        END IF;

    ELSE
        RETURN NEW;
    END IF;

    IF audit_actor IS NULL THEN
        RAISE EXCEPTION
            'Payroll audit actor is required.';
    END IF;

    audit_details := jsonb_build_object(
        'period_start', NEW.period_start,
        'period_end', NEW.period_end,
        'pay_frequency', NEW.pay_frequency_snapshot,
        'gross_pay', NEW.gross_pay_snapshot,
        'total_deductions', NEW.total_deductions_snapshot,
        'estimated_net', NEW.estimated_net_snapshot,
        'cancellation_reason', NEW.cancellation_reason,
        'cancelled_at', NEW.cancelled_at
    );

    INSERT INTO public.employee_payroll_period_history (
        spa_id,
        business_unit_id,
        employee_id,
        pay_period_id,
        action_type,
        previous_status,
        new_status,
        details_json,
        actor_user_id
    )
    VALUES (
        NEW.spa_id,
        NEW.business_unit_id,
        NEW.employee_id,
        NEW.pay_period_id,
        audit_action,
        prior_status,
        NEW.status,
        audit_details,
        audit_actor
    );

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payroll_history_period_created
AFTER INSERT
ON public.employee_payroll_periods
FOR EACH ROW
EXECUTE FUNCTION
    public.audit_employee_payroll_period();

