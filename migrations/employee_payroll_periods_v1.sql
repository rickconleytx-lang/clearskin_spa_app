-- =====================================================
-- DRAFT ALLOCATION AUTOMATIC AUDIT
-- =====================================================

CREATE FUNCTION public.audit_employee_payroll_draft_allocation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    audit_actor INTEGER;
    audit_action VARCHAR(80);
    removal_actor_text TEXT;
    entry_row public.employee_payroll_period_entries%ROWTYPE;
BEGIN
    IF TG_OP = 'INSERT' THEN
        entry_row := NEW;
        audit_actor := NEW.created_by_user_id;
        audit_action := 'draft_allocation_added';
    ELSE
        entry_row := OLD;
        audit_action := 'draft_allocation_removed';

        removal_actor_text := NULLIF(
            BTRIM(
                COALESCE(
                    current_setting(
                        'psp.payroll_removal_actor', true
                    ),
                    ''
                )
            ),
            ''
        );

        IF removal_actor_text IS NULL THEN
            RAISE EXCEPTION
                'Draft allocation removal requires '
                'an authenticated acting user.'
                USING ERRCODE = '23514';
        END IF;

        -- Resolve the actor through the users table,
        -- avoiding unverified numeric casts.
        SELECT u.user_id
        INTO audit_actor
        FROM public.users u
        WHERE u.user_id::TEXT = removal_actor_text;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Draft allocation removal actor '
                'does not exist.'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF audit_actor IS NULL THEN
        RAISE EXCEPTION
            'Draft allocation audit actor is required.'
            USING ERRCODE = '23514';
    END IF;

    INSERT INTO public.employee_payroll_period_history (
        spa_id,
        business_unit_id,
        employee_id,
        pay_period_id,
        action_type,
        previous_status,
        new_status,
        details_json,
        actor_user_id
    )
    VALUES (
        entry_row.spa_id,
        entry_row.business_unit_id,
        entry_row.employee_id,
        entry_row.pay_period_id,
        audit_action,
        'draft',
        'draft',
        jsonb_build_object(
            'period_entry_id', entry_row.period_entry_id,
            'work_entry_id', entry_row.work_entry_id,
            'work_date', entry_row.work_date_snapshot,
            'entry_type', entry_row.entry_type_snapshot,
            'regular_hours',
                entry_row.regular_hours_snapshot,
            'overtime_hours',
                entry_row.overtime_hours_snapshot,
            'days_worked',
                entry_row.days_worked_snapshot,
            'gross_amount',
                entry_row.gross_amount_snapshot
        ),
        audit_actor
    );

    IF TG_OP = 'INSERT' THEN
        RETURN NEW;
    END IF;

    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_payroll_audit_draft_allocation
AFTER INSERT OR DELETE
ON public.employee_payroll_period_entries
FOR EACH ROW
EXECUTE FUNCTION
    public.audit_employee_payroll_draft_allocation();


-- =====================================================
-- ATTRIBUTED DRAFT ALLOCATION REMOVAL
--
-- Application callers must obtain p_actor_user_id
-- from their authenticated PSP session.
-- =====================================================

CREATE FUNCTION public.remove_employee_payroll_draft_allocation(
    p_period_entry_id BIGINT,
    p_spa_id INTEGER,
    p_business_unit_id INTEGER,
    p_employee_id INTEGER,
    p_actor_user_id INTEGER
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    previous_removal_actor TEXT;
    removed_count INTEGER;
BEGIN
    IF p_actor_user_id IS NULL
       OR NOT EXISTS (
           SELECT 1
           FROM public.users u
           WHERE u.user_id = p_actor_user_id
       )
    THEN
        RAISE EXCEPTION
            'Draft allocation removal requires '
            'a valid acting user.'
            USING ERRCODE = '23514';
    END IF;

    previous_removal_actor :=
        current_setting('psp.payroll_removal_actor', true);

    PERFORM set_config(
        'psp.payroll_removal_actor',
        p_actor_user_id::TEXT,
        true
    );

    DELETE FROM public.employee_payroll_period_entries pe
    WHERE pe.period_entry_id = p_period_entry_id
      AND pe.spa_id = p_spa_id
      AND pe.business_unit_id = p_business_unit_id
      AND pe.employee_id = p_employee_id;

    GET DIAGNOSTICS removed_count = ROW_COUNT;

    PERFORM set_config(
        'psp.payroll_removal_actor',
        COALESCE(previous_removal_actor, ''),
        true
    );

    IF removed_count <> 1 THEN
        RAISE EXCEPTION
            'Matching Draft payroll allocation not found.'
            USING ERRCODE = '23514';
    END IF;
END;
$$;


-- =====================================================
-- AUTOMATIC DRAFT PAY PERIOD CHANGE AUDIT
--
-- The application must set the authenticated acting
-- user with set_config(..., true) in the SAME database
-- transaction as the Draft UPDATE.
--
-- Never derive this value from a user-editable field.
-- =====================================================

CREATE FUNCTION public.audit_employee_payroll_draft_update()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    changed_fields JSONB;
    actor_text TEXT;
    audit_actor INTEGER;
BEGIN
    -- Status transitions have their own audit triggers.
    IF OLD.status <> 'draft'
       OR NEW.status <> 'draft'
    THEN
        RETURN NEW;
    END IF;

    -- Build a before/after snapshot of each changed field.
    -- A change to updated_at alone is housekeeping, not
    -- a meaningful payroll modification.
    SELECT jsonb_object_agg(
        previous.key,
        jsonb_build_object(
            'before', previous.value,
            'after', current_row.value
        )
    )
    INTO changed_fields
    FROM jsonb_each(
        to_jsonb(OLD) - 'updated_at'
    ) AS previous(key, value)
    JOIN jsonb_each(
        to_jsonb(NEW) - 'updated_at'
    ) AS current_row(key, value)
      ON current_row.key = previous.key
    WHERE previous.value IS DISTINCT FROM current_row.value;

    IF changed_fields IS NULL THEN
        RETURN NEW;
    END IF;

    -- Require a fresh transaction-level actor rather
    -- than trusting a previously saved updater field.
    actor_text := NULLIF(
        BTRIM(
            COALESCE(
                current_setting(
                    'psp.payroll_draft_update_actor',
                    true
                ),
                ''
            )
        ),
        ''
    );

    IF actor_text IS NULL THEN
        RAISE EXCEPTION
            'Draft payroll changes require an '
            'authenticated acting user.'
            USING ERRCODE = '23514';
    END IF;

    SELECT u.user_id
    INTO audit_actor
    FROM public.users u
    WHERE u.user_id::TEXT = actor_text;

    IF audit_actor IS NULL
       OR NEW.updated_by_user_id
          IS DISTINCT FROM audit_actor
    THEN
        RAISE EXCEPTION
            'Draft payroll updater must match '
            'the authenticated acting user.'
            USING ERRCODE = '23514';
    END IF;

    INSERT INTO public.employee_payroll_period_history (
        spa_id,
        business_unit_id,
        employee_id,
        pay_period_id,
        action_type,
        previous_status,
        new_status,
        details_json,
        actor_user_id
    )
    VALUES (
        NEW.spa_id,
        NEW.business_unit_id,
        NEW.employee_id,
        NEW.pay_period_id,
        'draft_period_updated',
        'draft',
        'draft',
        jsonb_build_object(
            'changes', changed_fields
        ),
        audit_actor
    );

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payroll_audit_draft_period_update
AFTER UPDATE
ON public.employee_payroll_periods
FOR EACH ROW
WHEN (
    OLD.status = 'draft'
    AND NEW.status = 'draft'
)
EXECUTE FUNCTION
    public.audit_employee_payroll_draft_update();


