-- =====================================================
-- EXTERNAL PAYMENT RECORD INTEGRITY
-- =====================================================

CREATE FUNCTION public.guard_employee_payroll_payment_record()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    period_row RECORD;
    target_spa_id INTEGER;
    target_unit_id INTEGER;
    target_employee_id INTEGER;
    target_period_id BIGINT;
BEGIN
    -- Payment evidence is never physically deleted.
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION
            'Payroll payment history cannot be deleted.'
            USING ERRCODE = '23514';
    END IF;

    target_spa_id := NEW.spa_id;
    target_unit_id := NEW.business_unit_id;
    target_employee_id := NEW.employee_id;
    target_period_id := NEW.pay_period_id;

    -- Serialize payment changes against period transitions.
    SELECT
        p.status,
        p.estimated_net_snapshot
    INTO period_row
    FROM public.employee_payroll_periods p
    WHERE p.spa_id = target_spa_id
      AND p.business_unit_id = target_unit_id
      AND p.employee_id = target_employee_id
      AND p.pay_period_id = target_period_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Matching payroll period not found.'
            USING ERRCODE = '23514';
    END IF;

    -- Payment evidence can be created or corrected
    -- only while payroll remains Approved.
    IF period_row.status <> 'approved' THEN
        RAISE EXCEPTION
            'Payment changes require Approved payroll.'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.reversed_at IS NOT NULL
           OR NEW.reversed_by_user_id IS NOT NULL
           OR NEW.reversal_reason IS NOT NULL
        THEN
            RAISE EXCEPTION
                'New payment evidence cannot start reversed.'
                USING ERRCODE = '23514';
        END IF;

        IF NEW.payment_amount
            IS DISTINCT FROM period_row.estimated_net_snapshot
        THEN
            RAISE EXCEPTION
                'Recorded payment must match estimated net pay.'
                USING ERRCODE = '23514';
        END IF;

        RETURN NEW;
    END IF;

    -- Existing payment evidence is immutable except
    -- for an explicit, attributed reversal.
    IF OLD.reversed_at IS NOT NULL THEN
        RAISE EXCEPTION
            'Reversed payroll payments are immutable.'
            USING ERRCODE = '23514';
    END IF;

    IF (
        to_jsonb(NEW) - ARRAY[
            'reversed_at',
            'reversed_by_user_id',
            'reversal_reason'
        ]
    ) IS DISTINCT FROM (
        to_jsonb(OLD) - ARRAY[
            'reversed_at',
            'reversed_by_user_id',
            'reversal_reason'
        ]
    ) THEN
        RAISE EXCEPTION
            'Payroll payment details cannot be edited.'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.reversed_at IS NULL
       OR NEW.reversed_by_user_id IS NULL
       OR NULLIF(BTRIM(NEW.reversal_reason), '') IS NULL
    THEN
        RAISE EXCEPTION
            'Payment reversal requires actor, date and reason.'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

