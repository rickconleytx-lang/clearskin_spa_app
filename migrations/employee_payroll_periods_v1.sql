CREATE TABLE public.employee_payroll_periods (
    pay_period_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    spa_id INTEGER NOT NULL,
    business_unit_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,

    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    pay_frequency_snapshot VARCHAR(20) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'draft',

    boundaries_confirmed_by_user_id INTEGER NOT NULL,
    boundaries_confirmed_at TIMESTAMPTZ NOT NULL
        DEFAULT NOW(),

    regular_hours_snapshot NUMERIC(10,2),
    overtime_hours_snapshot NUMERIC(10,2),
    days_worked_snapshot NUMERIC(10,2),
    event_count_snapshot INTEGER,

    gross_pay_snapshot NUMERIC(14,2),

    fica_percent_snapshot NUMERIC(7,4),
    fica_amount_snapshot NUMERIC(14,2),

    deduction_1_title_snapshot VARCHAR(150),
    deduction_1_amount_snapshot NUMERIC(14,2),

    deduction_2_title_snapshot VARCHAR(150),
    deduction_2_amount_snapshot NUMERIC(14,2),

    total_deductions_snapshot NUMERIC(14,2),
    estimated_net_snapshot NUMERIC(14,2),

    calculated_at TIMESTAMPTZ,

    created_by_user_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_by_user_id INTEGER,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    approved_by_user_id INTEGER,
    approved_at TIMESTAMPTZ,

    paid_by_user_id INTEGER,
    paid_at TIMESTAMPTZ,

    cancelled_by_user_id INTEGER,
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT,

    CONSTRAINT fk_payroll_period_employee
        FOREIGN KEY (
            spa_id, business_unit_id, employee_id
        )
        REFERENCES public.employee_business_unit_memberships (
            spa_id, business_unit_id, employee_id
        )
        ON DELETE RESTRICT,

    CONSTRAINT fk_payroll_period_creator
        FOREIGN KEY (created_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT fk_payroll_period_updater
        FOREIGN KEY (updated_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT fk_payroll_period_confirmed_by
        FOREIGN KEY (boundaries_confirmed_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT fk_payroll_period_approved_by
        FOREIGN KEY (approved_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT fk_payroll_period_paid_by
        FOREIGN KEY (paid_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT fk_payroll_period_cancelled_by
        FOREIGN KEY (cancelled_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT chk_payroll_period_dates
        CHECK (period_end >= period_start),

    CONSTRAINT chk_payroll_period_frequency
        CHECK (
            pay_frequency_snapshot IN (
                'weekly',
                'biweekly',
                'semimonthly',
                'monthly'
            )
        ),

    CONSTRAINT chk_payroll_period_status
        CHECK (
            status IN ('draft', 'approved', 'paid', 'cancelled')
        ),

    CONSTRAINT chk_payroll_period_cancelled
        CHECK (
            (
                status <> 'cancelled'
                AND cancelled_by_user_id IS NULL
                AND cancelled_at IS NULL
                AND cancellation_reason IS NULL
            )
            OR (
                status = 'cancelled'
                AND cancelled_by_user_id IS NOT NULL
                AND cancelled_at IS NOT NULL
                AND NULLIF(
                    BTRIM(cancellation_reason), ''
                ) IS NOT NULL
                AND approved_by_user_id IS NULL
                AND approved_at IS NULL
                AND paid_by_user_id IS NULL
                AND paid_at IS NULL
            )
        ),

    CONSTRAINT chk_payroll_period_fica
        CHECK (
            fica_percent_snapshot IS NULL
            OR fica_percent_snapshot BETWEEN 0 AND 100
        ),

    CONSTRAINT chk_payroll_period_amounts
        CHECK (
            (gross_pay_snapshot IS NULL
                OR gross_pay_snapshot >= 0)
            AND (fica_amount_snapshot IS NULL
                OR fica_amount_snapshot >= 0)
            AND (deduction_1_amount_snapshot IS NULL
                OR deduction_1_amount_snapshot >= 0)
            AND (deduction_2_amount_snapshot IS NULL
                OR deduction_2_amount_snapshot >= 0)
            AND (total_deductions_snapshot IS NULL
                OR total_deductions_snapshot >= 0)
            AND (estimated_net_snapshot IS NULL
                OR estimated_net_snapshot >= 0)
        ),

    CONSTRAINT chk_payroll_period_approved
        CHECK (
            status IN ('draft', 'cancelled')
            OR (
                calculated_at IS NOT NULL
                AND gross_pay_snapshot IS NOT NULL
                AND fica_percent_snapshot IS NOT NULL
                AND fica_amount_snapshot IS NOT NULL
                AND total_deductions_snapshot IS NOT NULL
                AND estimated_net_snapshot IS NOT NULL
                AND approved_by_user_id IS NOT NULL
                AND approved_at IS NOT NULL
            )
        ),

    CONSTRAINT chk_payroll_period_paid
        CHECK (
            status <> 'paid'
            OR (
                paid_by_user_id IS NOT NULL
                AND paid_at IS NOT NULL
            )
        ),

    CONSTRAINT uq_payroll_period_scope_id
        UNIQUE (
            spa_id,
            business_unit_id,
            employee_id,
            pay_period_id
        )
);

