CREATE UNIQUE INDEX uq_payroll_period_active_employee_dates
    ON public.employee_payroll_periods (
        spa_id,
        business_unit_id,
        employee_id,
        period_start,
        period_end
    )
    WHERE status <> 'cancelled';

-- =====================================================
-- PAY PERIOD OVERLAP PROTECTION
-- =====================================================

CREATE FUNCTION public.enforce_employee_payroll_period_no_overlap()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- Serialize pay-period changes for this employee
    -- to prevent concurrent overlapping inserts.
    PERFORM 1
    FROM public.employee_business_unit_memberships
    WHERE spa_id = NEW.spa_id
      AND business_unit_id = NEW.business_unit_id
      AND employee_id = NEW.employee_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Employee workspace membership not found.';
    END IF;

    IF NEW.status <> 'cancelled' AND EXISTS (
        SELECT 1
        FROM public.employee_payroll_periods p
        WHERE p.spa_id = NEW.spa_id
          AND p.business_unit_id = NEW.business_unit_id
          AND p.employee_id = NEW.employee_id
          AND p.status <> 'cancelled'
          AND p.pay_period_id IS DISTINCT FROM
              NEW.pay_period_id
          AND p.period_start <= NEW.period_end
          AND p.period_end >= NEW.period_start
    ) THEN
        RAISE EXCEPTION
            'Overlapping employee payroll periods are not allowed.'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payroll_period_no_overlap
BEFORE INSERT OR UPDATE OF
    spa_id,
    business_unit_id,
    employee_id,
    period_start,
    period_end
ON public.employee_payroll_periods
FOR EACH ROW
EXECUTE FUNCTION
    public.enforce_employee_payroll_period_no_overlap();


-- =====================================================
-- PAY PERIOD LIFECYCLE PROTECTION
-- =====================================================

CREATE FUNCTION public.guard_employee_payroll_period_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    previous_removal_actor TEXT;
    initial_actor_text TEXT;
    initial_actor_id INTEGER;
    initial_confirmation TEXT;

BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'draft'
           OR NEW.approved_at IS NOT NULL
           OR NEW.approved_by_user_id IS NOT NULL
           OR NEW.paid_at IS NOT NULL
           OR NEW.paid_by_user_id IS NOT NULL
        THEN
            RAISE EXCEPTION
                'New payroll periods must begin as Draft.'
            USING ERRCODE = '23514';
        END IF;

        -- Initial pay-period dates and frequency
        -- require explicit authenticated confirmation.
        initial_actor_text := NULLIF(
            BTRIM(
                COALESCE(
                    current_setting(
                        'psp.payroll_draft_update_actor',
                        true
                    ),
                    ''
                )
            ),
            ''
        );

        initial_confirmation := current_setting(
            'psp.payroll_boundaries_confirmed',
            true
        );

        IF initial_actor_text IS NULL
           OR initial_confirmation IS DISTINCT FROM 'yes'
        THEN
            RAISE EXCEPTION
                'Initial payroll boundaries require fresh confirmation.'
                USING ERRCODE = '23514';
        END IF;

        SELECT u.user_id
        INTO initial_actor_id
        FROM public.users u
        WHERE u.user_id::TEXT = initial_actor_text;

        IF initial_actor_id IS NULL
           OR NEW.created_by_user_id
               IS DISTINCT FROM initial_actor_id
           OR NEW.boundaries_confirmed_by_user_id
               IS DISTINCT FROM initial_actor_id
        THEN
            RAISE EXCEPTION
                'Initial payroll confirmation actor must match '
                'the authenticated creator.'
                USING ERRCODE = '23514';
        END IF;

        -- PostgreSQL controls the confirmation timestamp.
        NEW.boundaries_confirmed_at := clock_timestamp();

        -- Consume the confirmation after one successful
        -- pay-period creation.
        PERFORM set_config(
            'psp.payroll_boundaries_confirmed',
            '',
            true
        );

        RETURN NEW;
    END IF;

    -- Original payroll creation evidence is immutable.
    -- Draft editing must not rewrite who created the
    -- record, when it was created, or its identity.
    IF TG_OP = 'UPDATE' THEN
        IF NEW.pay_period_id
                IS DISTINCT FROM OLD.pay_period_id
           OR NEW.created_by_user_id
                IS DISTINCT FROM OLD.created_by_user_id
           OR NEW.created_at
                IS DISTINCT FROM OLD.created_at
        THEN
            RAISE EXCEPTION
                'Original payroll creation evidence '
                'is immutable.'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        IF OLD.status IN ('draft', 'approved', 'paid', 'cancelled') THEN
            RAISE EXCEPTION
                'Payroll periods cannot be deleted; use Cancel Draft instead.'
            USING ERRCODE = '23514';
        END IF;

        RETURN OLD;
    END IF;

    IF OLD.status = 'cancelled' THEN
        RAISE EXCEPTION
            'Cancelled payroll is immutable.'
            USING ERRCODE = '23514';
    END IF;

    IF OLD.status = 'paid' THEN
        RAISE EXCEPTION
            'Paid payroll is immutable. Use an audited correction.'
            USING ERRCODE = '23514';
    END IF;

    IF OLD.status = 'approved' THEN
        IF NEW.status <> 'paid' THEN
            RAISE EXCEPTION
                'Approved payroll may only transition to Paid.'
            USING ERRCODE = '23514';
        END IF;

        -- Only payment-status metadata may change.
        -- Financial snapshots and approval evidence stay fixed.
        IF (
            to_jsonb(NEW) - ARRAY[
                'status',
                'paid_by_user_id',
                'paid_at',
                'updated_by_user_id',
                'updated_at'
            ]
        ) IS DISTINCT FROM (
            to_jsonb(OLD) - ARRAY[
                'status',
                'paid_by_user_id',
                'paid_at',
                'updated_by_user_id',
                'updated_at'
            ]
        ) THEN
            RAISE EXCEPTION
                'Approved payroll snapshots cannot change.'
            USING ERRCODE = '23514';
        END IF;

        IF NEW.paid_by_user_id IS NULL
           OR NEW.paid_at IS NULL
        THEN
            RAISE EXCEPTION
                'Recording Paid requires payment attribution.'
            USING ERRCODE = '23514';
        END IF;

        RETURN NEW;
    END IF;

    IF OLD.status = 'draft' THEN
        IF NEW.status NOT IN (
            'draft', 'approved', 'cancelled'
        ) THEN
            RAISE EXCEPTION
                'Invalid payroll status transition.'
            USING ERRCODE = '23514';
        END IF;

        IF NEW.status = 'draft' THEN
            IF NEW.approved_at IS NOT NULL
               OR NEW.approved_by_user_id IS NOT NULL
               OR NEW.paid_at IS NOT NULL
               OR NEW.paid_by_user_id IS NOT NULL
            THEN
                RAISE EXCEPTION
                    'Draft payroll cannot contain approval or payment evidence.'
            USING ERRCODE = '23514';
            END IF;
        END IF;

        IF NEW.status = 'cancelled' THEN

            IF NEW.cancelled_by_user_id IS NULL
               OR NEW.cancelled_at IS NULL
               OR NULLIF(
                   BTRIM(NEW.cancellation_reason), ''
               ) IS NULL
            THEN
                RAISE EXCEPTION
                    'Cancel Draft requires actor, date and reason.'
                    USING ERRCODE = '23514';
            END IF;

            -- Cancellation cannot rewrite Draft financial
            -- information or period boundaries.
            IF (
                to_jsonb(NEW) - ARRAY[
                    'status',
                    'cancelled_by_user_id',
                    'cancelled_at',
                    'cancellation_reason',
                    'updated_by_user_id',
                    'updated_at'
                ]
            ) IS DISTINCT FROM (
                to_jsonb(OLD) - ARRAY[
                    'status',
                    'cancelled_by_user_id',
                    'cancelled_at',
                    'cancellation_reason',
                    'updated_by_user_id',
                    'updated_at'
                ]
            ) THEN
                RAISE EXCEPTION
                    'Cancel Draft cannot alter payroll details.'
                    USING ERRCODE = '23514';
            END IF;

            -- Preserve which work entries were released.
            -- The audit event and release are transactional.
            INSERT INTO public.employee_payroll_period_history (
                spa_id,
                business_unit_id,
                employee_id,
                pay_period_id,
                action_type,
                previous_status,
                new_status,
                details_json,
                actor_user_id
            )
            SELECT
                NEW.spa_id,
                NEW.business_unit_id,
                NEW.employee_id,
                NEW.pay_period_id,
                'draft_allocations_released',
                'draft',
                'draft',
                jsonb_build_object(
                    'released_entries',
                    jsonb_agg(
                        jsonb_build_object(
                            'work_entry_id', pe.work_entry_id,
                            'gross_amount',
                                pe.gross_amount_snapshot
                        )
                        ORDER BY pe.work_entry_id
                    )
                ),
                NEW.cancelled_by_user_id
            FROM public.employee_payroll_period_entries pe
            WHERE pe.pay_period_id = OLD.pay_period_id
              AND pe.spa_id = OLD.spa_id
              AND pe.business_unit_id = OLD.business_unit_id
              AND pe.employee_id = OLD.employee_id
            HAVING COUNT(*) > 0;

            -- Release work entries while the parent is
            -- still Draft. Existing allocation guards
            -- enforce the Draft-only restriction.
            -- Attribute each released allocation to the
            -- manager cancelling this Draft.
            previous_removal_actor :=
                current_setting(
                    'psp.payroll_removal_actor', true
                );

            PERFORM set_config(
                'psp.payroll_removal_actor',
                NEW.cancelled_by_user_id::TEXT,
                true
            );

            DELETE FROM public.employee_payroll_period_entries
            WHERE pay_period_id = OLD.pay_period_id
              AND spa_id = OLD.spa_id
              AND business_unit_id = OLD.business_unit_id
              AND employee_id = OLD.employee_id;

            -- Restore the preceding transaction context.
            PERFORM set_config(
                'psp.payroll_removal_actor',
                COALESCE(previous_removal_actor, ''),
                true
            );

            RETURN NEW;
        END IF;

        IF NEW.status = 'approved' THEN
            IF NEW.paid_at IS NOT NULL
               OR NEW.paid_by_user_id IS NOT NULL
            THEN
                RAISE EXCEPTION
                    'Approved payroll cannot already be marked Paid.'
            USING ERRCODE = '23514';
            END IF;
        END IF;

        RETURN NEW;
    END IF;

    RAISE EXCEPTION
        'Unrecognized payroll lifecycle state.'
            USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_payroll_period_lifecycle
BEFORE INSERT OR UPDATE OR DELETE
ON public.employee_payroll_periods
FOR EACH ROW
EXECUTE FUNCTION
    public.guard_employee_payroll_period_lifecycle();


