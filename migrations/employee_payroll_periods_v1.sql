CREATE TABLE public.employee_payroll_period_entries (
    period_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    spa_id INTEGER NOT NULL,
    business_unit_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,

    pay_period_id BIGINT NOT NULL,
    work_entry_id BIGINT NOT NULL,

    work_date_snapshot DATE NOT NULL,
    entry_type_snapshot VARCHAR(20) NOT NULL,

    regular_hours_snapshot NUMERIC(10,2) NOT NULL DEFAULT 0,
    overtime_hours_snapshot NUMERIC(10,2) NOT NULL DEFAULT 0,
    days_worked_snapshot NUMERIC(10,2) NOT NULL DEFAULT 0,

    rate_snapshot NUMERIC(14,2) NOT NULL,
    overtime_rate_snapshot NUMERIC(14,2),
    event_name_snapshot VARCHAR(200),

    gross_amount_snapshot NUMERIC(14,2) NOT NULL,

    created_by_user_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_payroll_period_entry_period
        FOREIGN KEY (
            spa_id, business_unit_id,
            employee_id, pay_period_id
        )
        REFERENCES public.employee_payroll_periods (
            spa_id, business_unit_id,
            employee_id, pay_period_id
        )
        ON DELETE RESTRICT,

    CONSTRAINT fk_payroll_period_entry_work
        FOREIGN KEY (
            spa_id, business_unit_id,
            employee_id, work_entry_id
        )
        REFERENCES public.employee_payroll_work_entries (
            spa_id, business_unit_id,
            employee_id, work_entry_id
        )
        ON DELETE RESTRICT,

    CONSTRAINT fk_payroll_period_entry_creator
        FOREIGN KEY (created_by_user_id)
        REFERENCES public.users(user_id),

    CONSTRAINT chk_payroll_period_entry_type
        CHECK (
            entry_type_snapshot IN (
                'hourly', 'daily', 'event'
            )
        ),

    CONSTRAINT chk_payroll_period_entry_amounts
        CHECK (
            regular_hours_snapshot >= 0
            AND overtime_hours_snapshot >= 0
            AND days_worked_snapshot >= 0
            AND rate_snapshot >= 0
            AND (
                overtime_rate_snapshot IS NULL
                OR overtime_rate_snapshot >= 0
            )
            AND gross_amount_snapshot >= 0
        ),

    -- One work entry cannot be allocated twice.
    CONSTRAINT uq_payroll_period_work_entry
        UNIQUE (work_entry_id)
);

CREATE INDEX idx_payroll_period_entries_period
    ON public.employee_payroll_period_entries (
        pay_period_id,
        work_date_snapshot
    );

-- =====================================================
-- PROTECT WORK ENTRIES ALLOCATED TO PAYROLL
-- =====================================================

CREATE FUNCTION public.guard_allocated_payroll_work_entry()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- A work entry already included in a pay period
    -- must not be changed, voided, or deleted.
    --
    -- Draft corrections require explicit removal from
    -- the saved pay period before editing the work entry.
    --
    -- Approved and Paid payroll associations will
    -- remain immutable.

    IF EXISTS (
        SELECT 1
        FROM public.employee_payroll_period_entries pe
        WHERE pe.spa_id = OLD.spa_id
          AND pe.business_unit_id = OLD.business_unit_id
          AND pe.employee_id = OLD.employee_id
          AND pe.work_entry_id = OLD.work_entry_id
    ) THEN
        RAISE EXCEPTION
            'Work entry belongs to a saved pay period. '
            'Remove it from Draft payroll before editing.'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payroll_allocated_work_entry_guard
BEFORE UPDATE OR DELETE
ON public.employee_payroll_work_entries
FOR EACH ROW
EXECUTE FUNCTION
    public.guard_allocated_payroll_work_entry();


-- =====================================================
-- PAY PERIOD ENTRY ALLOCATION PROTECTION
-- =====================================================

CREATE FUNCTION public.guard_payroll_period_entry_allocation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    period_row RECORD;
    work_row RECORD;
    target_period_id BIGINT;
    target_spa_id INTEGER;
    target_unit_id INTEGER;
    target_employee_id INTEGER;
    calculated_gross NUMERIC(14,2);
BEGIN
    -- Allocation changes use explicit removal and
    -- reinsertion while the pay period is Draft.
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION
            'Payroll allocations cannot be edited directly.'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'DELETE' THEN
        target_period_id := OLD.pay_period_id;
        target_spa_id := OLD.spa_id;
        target_unit_id := OLD.business_unit_id;
        target_employee_id := OLD.employee_id;
    ELSE
        target_period_id := NEW.pay_period_id;
        target_spa_id := NEW.spa_id;
        target_unit_id := NEW.business_unit_id;
        target_employee_id := NEW.employee_id;
    END IF;

    -- Lock the parent period to serialize allocation
    -- changes against approval or payment transitions.
    SELECT
        p.status,
        p.period_start,
        p.period_end
    INTO period_row
    FROM public.employee_payroll_periods p
    WHERE p.pay_period_id = target_period_id
      AND p.spa_id = target_spa_id
      AND p.business_unit_id = target_unit_id
      AND p.employee_id = target_employee_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Matching employee pay period not found.'
            USING ERRCODE = '23514';
    END IF;

    IF period_row.status <> 'draft' THEN
        RAISE EXCEPTION
            'Approved or Paid payroll allocations are locked.'
            USING ERRCODE = '23514';
    END IF;

    -- Draft allocations may be removed explicitly.
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    -- Lock the original work entry before validating
    -- and allocating it. This prevents concurrent edits
    -- from invalidating the new payroll snapshot.
    SELECT w.*
    INTO work_row
    FROM public.employee_payroll_work_entries w
    WHERE w.work_entry_id = NEW.work_entry_id
      AND w.spa_id = NEW.spa_id
      AND w.business_unit_id = NEW.business_unit_id
      AND w.employee_id = NEW.employee_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Matching payroll work entry not found.'
            USING ERRCODE = '23514';
    END IF;

    IF work_row.voided_at IS NOT NULL THEN
        RAISE EXCEPTION
            'Voided work entries cannot be allocated.'
            USING ERRCODE = '23514';
    END IF;

    IF work_row.work_date < period_row.period_start
       OR work_row.work_date > period_row.period_end
    THEN
        RAISE EXCEPTION
            'Work entry date is outside the pay period.'
            USING ERRCODE = '23514';
    END IF;

    -- Open clock entries are not payable until completed.
    IF work_row.clock_in_at IS NOT NULL
       AND work_row.clock_out_at IS NULL
    THEN
        RAISE EXCEPTION
            'Incomplete clock entries cannot be allocated.'
            USING ERRCODE = '23514';
    END IF;

    -- The saved line must match the original work entry.
    IF NEW.work_date_snapshot
            IS DISTINCT FROM work_row.work_date
       OR NEW.entry_type_snapshot
            IS DISTINCT FROM work_row.entry_type
       OR NEW.regular_hours_snapshot
            IS DISTINCT FROM work_row.regular_hours
       OR NEW.overtime_hours_snapshot
            IS DISTINCT FROM work_row.overtime_hours
       OR NEW.days_worked_snapshot
            IS DISTINCT FROM work_row.days_worked
       OR NEW.rate_snapshot
            IS DISTINCT FROM work_row.rate_snapshot
       OR NEW.overtime_rate_snapshot
            IS DISTINCT FROM work_row.overtime_rate_snapshot
       OR NEW.event_name_snapshot
            IS DISTINCT FROM work_row.event_name_snapshot
    THEN
        RAISE EXCEPTION
            'Payroll earning snapshots do not match the work entry.'
            USING ERRCODE = '23514';
    END IF;

    calculated_gross := ROUND(
        CASE
            WHEN work_row.entry_type = 'hourly'
            THEN
                work_row.regular_hours * work_row.rate_snapshot
                + work_row.overtime_hours
                  * COALESCE(
                      work_row.overtime_rate_snapshot, 0
                    )
            WHEN work_row.entry_type = 'daily'
            THEN
                work_row.days_worked * work_row.rate_snapshot
            WHEN work_row.entry_type = 'event'
            THEN work_row.rate_snapshot
            ELSE 0
        END,
        2
    );

    IF NEW.gross_amount_snapshot
        IS DISTINCT FROM calculated_gross
    THEN
        RAISE EXCEPTION
            'Payroll gross snapshot does not match calculated earnings.'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

