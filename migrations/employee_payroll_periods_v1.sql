    IF matching_payments <> 1 THEN
        RAISE EXCEPTION
            'Payroll cannot be marked Paid without '
            'one matching active recorded payment.'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

